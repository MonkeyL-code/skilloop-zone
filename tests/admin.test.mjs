import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import vm from 'node:vm';
import { articles, domains } from '../src/data.js';
import { transitionContent, CONTENT_KEY, refreshEditorialSeeds } from '../src/content.js';

test('reused admin can edit bilingual content, save privately, publish and withdraw', async () => {
  const html=await readFile(new URL('../admin/index.html',import.meta.url),'utf8');
  const d=new JSDOM(html,{url:'http://localhost/admin/',runScripts:'outside-only',pretendToBeVisual:true});const w=d.window;
  assert.deepEqual([...w.document.scripts].map(s=>s.getAttribute('src')),['demo-runtime.js'],'后台仅通过演示运行时启动，不能重复加载旧脚本');
  w.structuredClone=structuredClone;w.matchMedia=()=>({matches:false});w.scrollTo=()=>{};w.CSS={escape:s=>s};
  const errors=[];w.addEventListener('error',e=>errors.push(e.error));
  const boot=(await readFile(new URL('../admin/demo-runtime.js',import.meta.url),'utf8')).replace(/^import[^\n]*\n/gm,'').split("for (const name of ['icons.js'")[0];
  vm.runInContext(`(()=>{const articles=${JSON.stringify(articles)};const domains=${JSON.stringify(domains)};const CONTENT_KEY=${JSON.stringify(CONTENT_KEY)};const transitionContent=${transitionContent.toString()};const refreshEditorialSeeds=${refreshEditorialSeeds.toString()};\n${boot}\n})()`,d.getInternalVMContext());
  for(const name of ['icons.js','rich-editor.js','autosave.js','content-safety.js','app.js','publication-checks.js','header-menu.js','demo-extras.js'])vm.runInContext(await readFile(new URL('../admin/'+name,import.meta.url),'utf8'),d.getInternalVMContext());
  const tick=()=>new Promise(resolve=>setTimeout(resolve,30));
  const click=selector=>{const el=w.document.querySelector(selector);assert.ok(el,selector);el.click();};
  const input=(selector,value)=>{const el=w.document.querySelector(selector);el.value=value;el.dispatchEvent(new w.Event('input',{bubbles:true}));};
  assert.equal(w.document.querySelectorAll('#scroll-published tbody tr').length,5);
  const before=JSON.parse(w.localStorage.getItem(CONTENT_KEY)).find(p=>p.slug==='seedance').publishedSnapshot.title;
  click('[data-act=new-content]');click('[data-channel-new="前沿资讯"]');
  input('#edit-title','一篇新的前沿文章');
  w.document.querySelector('#edit-body').innerHTML='<p>新的中文正文。</p>';w.document.querySelector('#edit-body').dispatchEvent(new w.Event('input',{bubbles:true}));
  click('[data-lang=en]');input('#edit-en-title','A new frontier story');
  assert.ok(w.document.querySelector('#english-editor .rich-toolbar'),'英文也使用富文本工具栏');
  w.document.querySelector('#edit-en-body').innerHTML='<p>A new English story.</p>';w.document.querySelector('#edit-en-body').dispatchEvent(new w.Event('input',{bubbles:true}));
  click('[data-local=save]');await tick();
  click('[data-local=preview]');
  assert.match(w.document.querySelector('.overlay:last-child .article-body').textContent,/A new frontier story/,'英文标签下预览当前语言');
  click('.overlay:last-child [data-local=close-preview]');
  let rows=JSON.parse(w.localStorage.getItem(CONTENT_KEY));
  const created=rows.find(p=>p.title==='一篇新的前沿文章');assert.ok(created);assert.equal(created.publishedSnapshot,null);
  assert.equal(rows.find(p=>p.slug==='seedance').publishedSnapshot.title,before);
  click('[data-local=check-release]');await tick();click('[data-close-check]');
  assert.equal(w.document.querySelector('[data-local=publish]').disabled,false);
  click('[data-local=publish]');click('.overlay:last-child [data-local=ok]');await tick();
  rows=JSON.parse(w.localStorage.getItem(CONTENT_KEY));assert.equal(rows.find(p=>p.id===created.id).publishedSnapshot.enTitle,'A new frontier story');
  click('[data-local=published]');
  click(`[data-act=withdraw][data-id="${created.id}"]`);input('#withdraw-reason','更新内容');click('[data-local=withdraw-confirm]');await tick();
  rows=JSON.parse(w.localStorage.getItem(CONTENT_KEY));assert.equal(rows.find(p=>p.id===created.id).publishedSnapshot,null);
  assert.deepEqual(errors,[]);
  w.close();
});
