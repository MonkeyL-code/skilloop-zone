import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';

test('a new visitor reads an article, follows its contextual exchange link and completes a demo exchange', async () => {
  const dom = new JSDOM(await readFile(new URL('../index.html', import.meta.url), 'utf8'), { url: 'http://localhost/#welcome', pretendToBeVisual: true });
  const w = dom.window;
  w.scrollTo = () => {};
  for (const name of ['document', 'window', 'location', 'localStorage', 'DOMParser', 'FormData']) globalThis[name] = name === 'window' ? w : w[name];
  Object.defineProperty(globalThis, 'navigator', { configurable: true, value: w.navigator });
  const errors=[];w.addEventListener('error',e=>errors.push(e.error));
  await import('../app.js');
  const tick = () => new Promise(resolve => w.setTimeout(resolve, 20));
  const go = async path => { w.location.hash = path; await tick(); };
  const click = selector => { const b=w.document.querySelector(selector);assert.ok(b,selector);b.click(); };
  assert.ok(w.document.querySelector('.entry-page'));
  assert.equal(w.document.querySelector('.entry-primary').getAttribute('href'),'#exchange','起始页的主入口是互助区');
  assert.equal(w.document.querySelectorAll('.landing-steps,.hero-board,.landing .story-grid').length,0,'Welcome 保持极简');
  await go('frontier'); assert.equal(w.document.querySelectorAll('.domain-tab').length,6);
  assert.equal(w.document.querySelectorAll('.briefing-item,.briefing-lead').length,5,'资讯首屏呈现五个领域');
  await go('article/seedance');
  assert.match(w.document.querySelector('.article-body').textContent,/Seedance/);
  const link=w.document.querySelector('.dual-panel.want').getAttribute('href');
  assert.match(link,/source=seedance/);await go(link.slice(1));
  assert.match(w.document.querySelector('.article-context').textContent,/Seedance/);
  assert.ok(w.document.querySelector('[role=tablist][aria-label="教与学"]'),'教与学可以切换');
  assert.equal(w.document.querySelectorAll('.spaces-nav [data-space]').length,5,'五个领域进入 Spaces');
  assert.ok(w.document.querySelector('.featured-topics a[href^="#topic/"]'),'精选话题进入讨论');
  assert.ok(w.document.querySelector('.upcoming-events a[href^="#activity/"]'),'即将开始的活动进入详情');
  const teachingLink=w.document.querySelector('[role=tab][data-mode=teach]').getAttribute('href');
  await go(teachingLink.slice(1));
  assert.equal(w.document.body.dataset.communityMode,'teach');
  assert.ok(w.document.querySelector('.teaching-workspace'));
  assert.equal(w.document.querySelectorAll('.community-feed').length,0,'教的页面以资料为主');
  assert.match(w.location.hash,/domain=visual/,'切换保留领域');
  assert.match(w.location.hash,/source=seedance/,'切换保留文章来源');
  await go(link.slice(1));
  assert.ok(w.document.querySelector('.my-loops'),'找人学默认从自己的 Loop 开始');
  await go(link.slice(1)+'&view=all');
  assert.ok(w.document.querySelector('.skill-box.want'));
  assert.ok(w.document.querySelector('.community-feed .topic-row'),'互助区以交流主题为主');
  const topicHref=w.document.querySelector('.topic-title').getAttribute('href');
  await go(topicHref.slice(1));
  assert.ok(w.document.querySelector('.topic-conversation'));
  assert.ok(w.document.querySelector('[data-action=reply-topic]'));
  click('[data-action=invite][data-id=axia][data-mode=credits]');
  assert.ok(w.document.querySelector('#login-form'));
  click('#login-submit');
  assert.ok(w.document.querySelector('#verify-submit'));
  click('#verify-submit');
  assert.ok(w.document.querySelector('#invite-form'));
  click('#invite-submit');await tick();
  assert.match(w.location.hash,/#order\//);
  click('[data-action=peer-accept]');
  click('[data-action=work]');
  w.document.querySelector('#work-text').value='保留原图，用蒙版替换背景，检查边缘。';
  click('#work-save');
  click('[data-action=confirm-order]');
  click('[data-action=peer-confirm]');
  assert.match(w.document.querySelector('.order-detail').textContent,/这次互助，完成了/);
  const stored=JSON.parse(w.localStorage.getItem('skilloop.demo.v1'));
  assert.equal(stored.users.you.balance,1);
  assert.equal(stored.orders[0].status,'completed');
  await go('exchange?intent=teach&domain=visual');
  const teachingForm=w.document.querySelector('#teaching-form');
  assert.ok(teachingForm);
  w.document.querySelector('#teach-offer').value='Photoshop';
  w.document.querySelector('#teach-level').value='S2';
  w.document.querySelector('#teach-bio').value='可以教蒙版与图层。';
  w.document.querySelector('#teach-available').checked=false;
  click('#teach-save');
  assert.equal(JSON.parse(w.localStorage.getItem('skilloop.demo.v1')).users.you.offer,'Photoshop');
  assert.equal(JSON.parse(w.localStorage.getItem('skilloop.demo.v1')).users.you.offerTitle,'可以教蒙版与图层。','教学范围独立于个人简介');
  assert.equal(JSON.parse(w.localStorage.getItem('skilloop.demo.v1')).users.you.bio,'想把自己的旅行照片修得更好一点。');
  await go('profile/you');
  assert.match(w.document.querySelector('.profile-card').textContent,/Photoshop/,'教学资料与个人技能卡同步');
  assert.match(w.document.querySelector('.profile-card').textContent,/可以教蒙版与图层/);
  assert.match(w.document.querySelector('.profile-card').textContent,/暂不接受新互助/,'公开技能卡显示暂停状态');
  await go('topic/travel-photos');
  click('[data-action=invite][data-mode=credits]');
  assert.match(w.document.querySelector('#invite-form').textContent,/我可以帮 TA/,'求助帖的回应是提供帮助');
  click('.modal-close');
  await go('tasks?track=Python');assert.equal(w.document.querySelectorAll('.track-step').length,5);
  await go('tasks?track=Photoshop');assert.equal(w.document.querySelectorAll('.track-step').length,5);
  await go('activities');click('[data-action=join-activity]');
  assert.ok(w.document.querySelector('[data-action=leave-activity]'));
  await go('activity/photo-walk');
  assert.match(w.document.querySelector('.activity-detail').textContent,/这一周/);
  assert.ok(w.document.querySelector('[data-action=leave-activity]'),'活动详情与列表报名状态同步');
  await go('topic/photo-mask');click('[data-action=reply-topic]');
  w.document.querySelector('#reply-body').value='我会一点 Python，可以先看看你的脚本。';
  click('#reply-submit');
  assert.match(w.document.querySelector('.conversation-replies').textContent,/先看看你的脚本/);
  await go('exchange');click('[data-action=new-topic]');
  assert.equal(w.document.querySelectorAll('.wizard-options button').length,6);
  assert.equal(w.document.querySelectorAll('#topic-form').length,0,'新手先做选择，不显示大表单');
  click('[data-choice="2"]');
  click('[data-choice="1"]');
  click('[data-choice="1"]');
  assert.ok(w.document.querySelector('.wizard-result'),'三题后才生成预览');
  w.document.querySelector('.wizard-edit').open=true;
  w.document.querySelector('#topic-title').value='找人一起整理自己的照片文件';
  w.document.querySelector('#topic-body').value='想先按月份分类，原文件保留不动。';
  click('#topic-submit');await tick();
  assert.match(w.document.querySelector('.my-loop-tab.selected').textContent,/整理自己的照片/);
  assert.ok(w.document.querySelector('.match-recommendations'),'发布后直接进入这条 Loop 的推荐');
  assert.deepEqual(errors,[]);
  dom.window.close();
});
